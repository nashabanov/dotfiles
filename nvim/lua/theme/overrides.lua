local M = {}

function M.apply()
    local hl = vim.api.nvim_set_hl

    ------------------------------------------------------------------
    -- Comments & Inlay hints
    ------------------------------------------------------------------

    hl(0, "Comment", {
        fg = "#667085",
        italic = true,
    })

    hl(0, "LspInlayHint", {
        fg = "#6C7486",
        bg = "NONE",
        italic = true,
    })

    ------------------------------------------------------------------
    -- Parameters
    ------------------------------------------------------------------

    hl(0, "@parameter", {
        fg = "#A8B4C2",
        italic = true,
    })

    hl(0, "@lsp.type.parameter", {
        fg = "#A8B4C2",
        italic = true,
    })

    ------------------------------------------------------------------
    -- Variables / Properties
    ------------------------------------------------------------------

    hl(0, "@property", {
        fg = "#63C5EA",
    })

    hl(0, "@variable.member", {
        fg = "#63C5EA",
    })

    hl(0, "@variable.builtin", {
        fg = "#8E98A6",
    })

    ------------------------------------------------------------------
    -- Types
    ------------------------------------------------------------------

    -- встроенные типы
    hl(0, "@type.builtin", {
        fg = "#D7DEE7",
    })

    -- пользовательские типы
    hl(0, "@type", {
        fg = "#C7D7E5",
    })

    hl(0, "@lsp.type.type", {
        fg = "#C7D7E5",
    })

    ------------------------------------------------------------------
    -- Classes
    ------------------------------------------------------------------

    hl(0, "@type.definition", {
        fg = "#8AD4FF",
        bold = true,
    })

    hl(0, "@lsp.type.class", {
        fg = "#8AD4FF",
        bold = true,
    })

    ------------------------------------------------------------------
    -- Functions
    ------------------------------------------------------------------

    hl(0, "@function", {
        fg = "#FFB454",
    })

    hl(0, "@function.call", {
        fg = "#FFB454",
    })

    hl(0, "@function.method", {
        fg = "#FFB454",
    })

    hl(0, "@constructor", {
        fg = "#FFD173",
    })

    ------------------------------------------------------------------
    -- Modules
    ------------------------------------------------------------------

    hl(0, "@module", {
        fg = "#7DA6C2",
    })

    hl(0, "@namespace", {
        fg = "#7DA6C2",
    })

    ------------------------------------------------------------------
    -- UI
    ------------------------------------------------------------------

    hl(0, "CursorLine", {
        bg = "#242B38",
    })

    hl(0, "NormalFloat", {
        bg = "#232937",
    })

    hl(0, "FloatBorder", {
        fg = "#404859",
        bg = "#232937",
    })

    ------------------------------------------------------------------
    -- Diagnostics
    ------------------------------------------------------------------

    hl(0, "DiagnosticVirtualTextHint", {
        fg = "#6C7486",
        bg = "NONE",
    })

    hl(0, "DiagnosticVirtualTextInfo", {
        bg = "NONE",
    })

    hl(0, "DiagnosticVirtualTextWarn", {
        bg = "NONE",
    })

    hl(0, "DiagnosticVirtualTextError", {
        bg = "NONE",
    })
end

return M
